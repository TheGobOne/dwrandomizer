#!/usr/bin/env python3
"""Assembles the Dn-FamiTracker driver and wrapper into common/ft_driver.h.
Usage: gen_driver.py CC65_BIN_DIR ASM6F_EXE (run from a scratch directory)

Layout of a music bank (banks 3 and 6 hold identical copies):
  $8000-$80ff  left free (bank 3 uses it)
  $8100-       driver, wrapper and tables
  FT_SONGS-    song data, different per bank
"""
import os, re, subprocess, sys

CC65, ASM = sys.argv[1:3]
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))

src = open(HERE + '/driver/driver.s', encoding='utf8').read()
line = [l for l in src.splitlines() if l.startswith('\t.addr * + 2')][0]
patched = src.replace('ft_music_addr:\n' + line, 'ft_music_addr = $6bf0')
assert patched != src
open(HERE + '/driver/driver2.s', 'w', encoding='utf8').write(patched)

open('drv.cfg', 'w').write('''MEMORY {
 ZP: start=$D0,size=$2E,type=rw,file="";
 RAM: start=$6900,size=$700,type=rw,file="";
 PRG: start=$8100,size=$3F00,type=ro,file=%O;
}
SEGMENTS {
 ZEROPAGE: load=ZP,type=zp;
 BSS: load=RAM,type=bss,define=yes;
 CODE: load=PRG,type=ro;
 DPCM: load=PRG,type=ro,optional=yes;
}
''')
subprocess.check_call([CC65 + '/ca65', '-g', HERE + '/driver/driver2.s', '-D', 'RELOCATE_MUSIC',
                       '-D', 'USE_OLDVIBRATO', '-D', 'NAMCO_CHANNELS=8', '-D', 'CHANNEL_CONTROL',
                       '-o', 'drv.o'])
subprocess.check_call([CC65 + '/ld65', '-o', 'drv.bin', '-C', 'drv.cfg', '-Ln', 'drv.lbl', 'drv.o'])
L = {m[2]: int(m[1], 16) for m in re.finditer(r'al (\w+) \.(\w+)', open('drv.lbl').read())}
D = open('drv.bin', 'rb').read()
W = 0x8100 + len(D)

open('wrap.asm', 'w').write(f'''
INIT={L['ft_music_init']}
PLAY={L['ft_music_play']}
CH={L['var_Channels']}
PF={L['var_ch_PrevFreqHigh']}
MA=$6bf0
DELAY=$6bf8
JG=$6bfa
BANKSEL=$6bf9
SONG=$6bfb
WANT=$6bfc
CUR=$6bfd
G=$6bfe
FA=$6bff
.base {W}
wrap:
 lda $fa
 sta FA
 ldx #$2d
s1: lda $d0,x
 sta $6b00,x
 lda $6b40,x
 sta $d0,x
 dex
 bpl s1
 lda $03bf
 cmp #$5a
 beq ok
 lda #$5a
 sta $03bf
 lda #$ff
 sta CUR
 sta SONG
ok:
 lda WANT
 cmp CUR
 beq same
 cmp #$0e
 bne go
 inc DELAY
 lda DELAY
 cmp #60
 bcs sting
 lda #$ff
 sta SONG
 jmp same
sting:
 lda WANT
go:
 and #$1f
 tax
 lda map,x
 bpl start
 sta SONG
 lda WANT
 sta CUR
 jmp same
start:
 tay
 lda #0
 sta JG
 lda banks,y
 cmp BANKSEL
 beq here
 sta BANKSEL
 lda #$ff
 sta SONG
 jmp same
here:
 lda WANT
 sta CUR
 sty SONG
 lda lo,y
 sta MA
 lda hi,y
 sta MA+1
 lda #0
 tax
 jsr INIT
same:
 lda SONG
 bmi out
 lda #$0f
 sta $4015
 lda FA
 beq idle
 lda #$f5
 sta CH
 lda #1
 sta G
 jmp pl
idle:
 lda #$ff
 sta CH
 lda #8
 sta $400f
 lda G
 beq pl
 lda #0
 sta G
 lda #$ff
 sta PF+1
pl:
 jsr PLAY
out:
 ldx #$2d
s2: lda $d0,x
 sta $6b40,x
 lda $6b00,x
 sta $d0,x
 dex
 bpl s2
 rts
map: .dsb 32,$ff
lo: .dsb 24,0
hi: .dsb 24,0
banks: .dsb 24,0
songs:
''')
subprocess.check_call([ASM, '-q', '-l', 'wrap.asm', 'wrap.bin'])
w = open('wrap.bin', 'rb').read()
image = D + w
# tables are the last 104 bytes of the wrapper
songs = W + len(w)
Map = songs - 104
out = ['/** Generated by tools/custom-music/gen_driver.py. Driver source: tools/custom-music/driver */',
       '#ifndef FT_DRIVER_H', '#define FT_DRIVER_H', '#include <stdint.h>',
       '#define FT_BASE 0x%04x' % 0x8100,
       '#define FT_WRAP 0x%04x' % W,
       '#define FT_MAP 0x%04x' % Map,
       '#define FT_LO 0x%04x' % (Map + 32),
       '#define FT_HI 0x%04x' % (Map + 56),
       '#define FT_BANKS 0x%04x' % (Map + 80),
       '#define FT_SONGS 0x%04x' % songs,
       'static const uint8_t ft_image[%d] = {' % len(image)]
for i in range(0, len(image), 16):
    out.append(' ' + ','.join('0x%02x' % b for b in image[i:i + 16]) + ',')
out += ['};', '#endif', '']
open(REPO + '/common/ft_driver.h', 'w', newline='\n').write('\n'.join(out))
print('driver', len(D), 'wrapper', len(w), 'songs at', hex(songs), 'room per bank', 0xc000 - songs)
